-- Cloud Bill Spike Explainer: SQLite schema (version 2)
--
-- Money is stored as TEXT holding an exact decimal string (e.g. '1234.5600').
-- SQLite has no DECIMAL type and REAL is binary floating point, which is exactly
-- what we must avoid for invoice reconciliation. Python converts with Decimal.
-- Dates are ISO 8601 text; timestamps are UTC ISO 8601 text.
-- Foreign keys are enforced per connection (PRAGMA set in database.connect()).

CREATE TABLE IF NOT EXISTS users (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    auth_provider    TEXT NOT NULL,               -- e.g. 'google'
    provider_subject TEXT NOT NULL,               -- OIDC "sub" claim: the stable identity key
    email            TEXT,                        -- informational only; can change
    created_at       TEXT NOT NULL,
    UNIQUE (auth_provider, provider_subject)
);

CREATE TABLE IF NOT EXISTS documents (
    id                      INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id                 INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    original_filename       TEXT NOT NULL,        -- display only; never used to build paths
    storage_path            TEXT NOT NULL UNIQUE, -- uuid-based name generated by us
    sha256                  TEXT NOT NULL CHECK (length(sha256) = 64),
    file_type               TEXT NOT NULL CHECK (file_type IN ('pdf','csv','xlsx','png','jpg')),
    file_size_bytes         INTEGER NOT NULL CHECK (file_size_bytes >= 0),
    uploaded_at             TEXT NOT NULL,
    account_alias           TEXT,
    cloud_provider          TEXT,                 -- 'aws' | 'azure' | 'gcp' | NULL (heuristic)
    billing_period_start    TEXT,
    billing_period_end      TEXT,
    status                  TEXT NOT NULL DEFAULT 'uploaded'
                            CHECK (status IN ('uploaded','processing','needs_review','processed','failed')),
    extracted_text          TEXT,
    validation_notes        TEXT NOT NULL DEFAULT '[]',   -- JSON list of strings
    supersedes_document_id  INTEGER REFERENCES documents(id) ON DELETE RESTRICT,
    verified_at             TEXT,
    UNIQUE (user_id, sha256),                     -- duplicate detection, per user
    CHECK (billing_period_start IS NULL OR billing_period_end IS NULL
           OR billing_period_end >= billing_period_start)
);
CREATE INDEX IF NOT EXISTS idx_documents_user_period
    ON documents (user_id, billing_period_start);

CREATE TABLE IF NOT EXISTS billing_line_items (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    document_id      INTEGER NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    service          TEXT,
    region           TEXT,
    resource_id      TEXT,
    charge_type      TEXT NOT NULL DEFAULT 'usage'
                     CHECK (charge_type IN ('usage','credit','tax','adjustment','fee','other')),
    usage_quantity   TEXT,                        -- exact decimal text, nullable
    usage_unit       TEXT,
    cost_amount      TEXT NOT NULL,               -- exact decimal text; credits are negative
    currency         TEXT NOT NULL CHECK (length(currency) = 3 AND currency = upper(currency)),
    period_start     TEXT,
    period_end       TEXT,
    source_locator   TEXT NOT NULL,               -- e.g. 'row 14', 'page 2', 'sheet Data!A7'
    raw_record       TEXT,                        -- original row/text as JSON, for provenance
    status           TEXT NOT NULL DEFAULT 'extracted'
                     CHECK (status IN ('extracted','needs_review','verified'))
);
CREATE INDEX IF NOT EXISTS idx_items_document ON billing_line_items (document_id);
CREATE INDEX IF NOT EXISTS idx_items_doc_service_region
    ON billing_line_items (document_id, service, region);

-- Every amount is nullable: if the invoice did not state it (or we could not read it
-- reliably) we store NULL and list the field in uncertain_fields. Never a guess.
CREATE TABLE IF NOT EXISTS invoice_summaries (
    document_id            INTEGER PRIMARY KEY REFERENCES documents(id) ON DELETE CASCADE,
    invoice_number         TEXT,
    currency               TEXT CHECK (currency IS NULL
                                       OR (length(currency) = 3 AND currency = upper(currency))),
    usage_total            TEXT,
    credit_total           TEXT,                  -- stored negative, shown separately (TC2)
    tax_total              TEXT,
    other_adjustments      TEXT,
    invoice_total          TEXT,
    reconciliation_status  TEXT NOT NULL DEFAULT 'not_checked'
                           CHECK (reconciliation_status IN
                                  ('not_checked','reconciled','mismatch','incomplete')),
    reconciliation_notes   TEXT,
    uncertain_fields       TEXT NOT NULL DEFAULT '[]'     -- JSON list of field names to review
);
